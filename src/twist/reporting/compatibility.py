"""Compatibility matrix of every registered explainer (plan §Week 5 deliverable), generated from
class metadata so it cannot drift from the code."""

from __future__ import annotations

from twist.explainers.registry import EXPLAINERS

PLANNED = [
    (
        "TSCausalCF",
        "baseline",
        "external (to be added by the authors)",
        "trajectory",
        "registered readings",
        "R5 (mechanism as residual penalty)",
        "—",
        "—",
        "—",
        "—",
        "planned",
    ),
]


def compatibility_markdown() -> str:
    head = (
        "| method | role | source | output | evaluated under | min regime | reference data | "
        "gradients | seeds matter | partially observed worlds | status |"
    )
    lines = [
        "# Explainer compatibility matrix",
        "",
        "Generated by `twist compat` from explainer metadata. *Output* is what the method returns. "
        "*Evaluated under* is how the benchmark obtains an action: the method's own declared action "
        "(`native`), or the registered diagnostic readings (never attributed to the method). "
        "*Partially observed worlds*: methods that abduct from observations are skipped there with "
        "a recorded reason.",
        "",
        head,
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, cls in sorted(
        EXPLAINERS.items(), key=lambda kv: (kv[1].is_control, kv[1].source != "twist", kv[0])
    ):
        role = cls.role or (
            "control" if cls.is_control else ("reference" if cls.source == "twist" else "baseline")
        )
        src = cls.source + (f" `{cls.upstream}`" if cls.upstream else "")
        out = "declared action + trajectory" if cls.native_actions else "trajectory"
        under = "native" if cls.native_actions else "registered readings"
        lines.append(
            f"| {name} | {role} | {src} | {out} | {under} | {cls.min_regime} | "
            f"{'yes' if cls.uses_reference_data else 'no'} | {'yes' if cls.uses_gradients else 'no'} | "
            f"{'yes' if cls.stochastic else 'no'} | {'skipped' if cls.exact_world_only else 'yes'} | available |"
        )
    for row in PLANNED:
        lines.append("| " + " | ".join(row) + " |")
    lines += [
        "",
        "All methods receive the same classifier interface (raw world units in, logits out; the "
        "classifier standardizes internally), the same per-unit budget (model queries, wall clock), "
        "and — from R1 — the same reference trajectories and labels (subsampled with the explainer "
        "seed). Every unit ends in a standardized explanation or a structured failure record "
        "(`no_target_flip`, `budget_exceeded`, `timeout`, `method_error`, `invalid_output`, "
        "`numerical_instability`, `abstain`).",
    ]
    return "\n".join(lines) + "\n"
